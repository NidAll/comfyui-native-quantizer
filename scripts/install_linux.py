#!/usr/bin/env python3
"""Install local launchers, desktop shortcuts and completions without pip/network."""
from __future__ import annotations

import argparse
import json
import os
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from native_quantizer.cli.arguments import build_arg_parser
from native_quantizer.cli.catalog import completions
from native_quantizer.config import load_defaults

MARKER = '# Generated by comfyui-native-quantizer'


def write(path: Path, content: str, mode: int, *, managed: bool = True) -> None:
    if managed and path.exists() and MARKER not in path.read_text(encoding='utf-8'):
        raise SystemExit(f'Refusing to replace an unrelated file: {path}')
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix='.' + path.name, dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as stream:
            stream.write(content)
        os.chmod(name, mode)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)
    print(path)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--python', default=sys.executable, help='existing ComfyUI Python interpreter')
    parser.add_argument('--prefix', type=Path, default=Path.home() / '.local')
    parser.add_argument('--config-home', type=Path, default=Path(os.environ.get('XDG_CONFIG_HOME') or Path.home() / '.config'))
    parser.add_argument('--cuda-default', action='store_true')
    parser.add_argument('--offline-default', action='store_true')
    args = parser.parse_args(argv)
    interpreter = Path(args.python).absolute()
    if not interpreter.is_file() or not os.access(interpreter, os.X_OK):
        parser.error('--python must be an existing executable interpreter')
    config = args.config_home / 'comfyui-native-quantizer/config.json'
    defaults = load_defaults(config) if config.exists() else {}
    if args.cuda_default:
        subprocess.run([str(interpreter), '-c', "import torch; assert torch.cuda.is_available() and torch.version.hip is None, 'CUDA is unavailable'"], check=True)
        defaults.update(device='cuda', target_runtime='nvidia')
    if args.offline_default:
        defaults['offline'] = True
    defaults.setdefault('max_memory', '512M')
    defaults.setdefault('progress', 'auto')
    # Compile generated modules before changing user files.
    for module in ['native_quantizer.cli.commands']:
        subprocess.run([str(interpreter), '-c', f'import sys; sys.path.insert(0, {str(ROOT)!r}); import {module}'], check=True)
    binaries = args.prefix / 'bin'
    data_home = Path(os.environ.get('XDG_DATA_HOME') or args.prefix / 'share')
    for name, module, invocation in [
        ('comfyquant', 'native_quantizer.cli.entrypoint', 'raise SystemExit(entrypoint())'),
        ('comfyui-native-quantizer', 'native_quantizer.cli.entrypoint', 'raise SystemExit(entrypoint())')]:
        entry = 'entrypoint'
        code = f'import sys; sys.path.insert(0, {str(ROOT)!r}); from {module} import {entry}; {invocation}'
        command = f'exec {shlex.quote(str(interpreter))} -c {shlex.quote(code)} "$@"'
        write(binaries / name, f'#!/bin/sh\n{MARKER}\n{command}\n', 0o755)
    config.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    write(config, json.dumps({'schema': 1, **defaults}, indent=2) + '\n', 0o600, managed=False)
    parser = build_arg_parser()
    for name in ('comfyquant', 'comfyui-native-quantizer'):
        fish = '\n'.join(line for line in completions(parser, 'fish').splitlines() if line.startswith(f'complete -c {name} '))
        write(args.config_home / f'fish/completions/{name}.fish', MARKER + '\n' + fish + '\n', 0o644)
        write(data_home / f'bash-completion/completions/{name}', MARKER + '\n' + completions(parser, 'bash'), 0o644)
    write(data_home / 'zsh/site-functions/_comfyquant', completions(parser, 'zsh').splitlines()[0] + '\n' + MARKER + '\n' + '\n'.join(completions(parser, 'zsh').splitlines()[1:]) + '\n', 0o644)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
